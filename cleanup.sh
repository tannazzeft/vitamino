#!/bin/bashk

# فایل هدف
FILE="app.py"

# 1. حذف خطوط خالی اضافی در ابتدا و انتها
sed -i '/^[[:space:]]*$/{x;/./{x;d;};x;}' $FILE

# 2. حذف کامنت‌های تک‌خطی (فقط اگر بعد از کد نیستند)
sed -i '/^[[:space:]]*\([^#]*[^[:space:]][^#]*\)\?#.*$/d' $FILE

# 3. تنظیم تورفتگی به 4 فاصله (حفظ ساختار کد)
sed -i 's/^[[:space:]]\{1,\}/    /' $FILE

# 4. حذف کاراکترهای غیرقابل چاپ (مثل ^M یا کاراکترهای مخفی)
sed -i 's/[\x00-\x1F\x7F-\xFF]//g' $FILE

# 5. بستن نقل‌قول‌های باز (ساده‌سازی)
sed -i 's/"[^"]*$/"/' $FILE
sed -i "s/'[^']*$/'/" $FILE

# 6. حذف خطوط ناقص یا بدون محتوای معنادار
sed -i '/^[[:space:][:punct:]]*$/d' $FILE

# 7. حذف تگ‌های HTML ناقص (در صورت وجود در st.markdown)
sed -i 's/<[^>]*$/<>/' $FILE

echo "تمیزکاری فایل $FILE با موفقیت انجام شد!"
